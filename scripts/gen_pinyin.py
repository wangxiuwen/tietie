"""Generate src/pinyinTable.ts — first-letter pinyin map for every GB2312
hanzi. Run once when the table needs regenerating:

    py -3 scripts/gen_pinyin.py

Output: `export const PINYIN_FIRST: Record<string, string> = { ... };`
Used by src/search.ts so queries like "nz" match 「内存」.
"""

import os
from pypinyin import lazy_pinyin

def gb2312_chars():
    chars = []
    for hi in range(0xB0, 0xF8):        # level-1/2 hanzi sections
        for lo in range(0xA1, 0xFF):
            try:
                chars.append(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return chars

def main():
    pairs = []
    for ch in gb2312_chars():
        py = lazy_pinyin(ch)
        if py and py[0] and py[0][0].isascii() and py[0][0].isalpha():
            pairs.append((ch, py[0][0].lower()))
    full = []
    for ch in gb2312_chars():
        py = lazy_pinyin(ch)
        if py and py[0] and py[0][0].isascii() and py[0][0].isalpha():
            full.append((ch, py[0].lower()))
    out = os.path.join(os.path.dirname(__file__), "..", "src", "pinyinTable.ts")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// AUTO-GENERATED by scripts/gen_pinyin.py — do not edit by hand.\n")
        f.write("// Pinyin for every GB2312 hanzi: first letters + full syllables.\n")
        f.write("export const PINYIN_FIRST: Record<string, string> = {\n")
        for i in range(0, len(pairs), 24):
            f.write("  " + " ".join(f'"{c}":"{a}",' for c, a in pairs[i:i + 24]) + "\n")
        f.write("};\n")
        f.write("\n// char → full pinyin syllable, e.g. 内→nei 存→cun\n")
        f.write("export const PINYIN_FULL: Record<string, string> = {\n")
        for i in range(0, len(full), 16):
            f.write("  " + " ".join(f'"{c}":"{a}",' for c, a in full[i:i + 16]) + "\n")
        f.write("};\n")
    print(f"wrote {len(pairs)} entries to {os.path.normpath(out)}")

if __name__ == "__main__":
    main()
